import assert from 'node:assert/strict';import fs from 'node:fs/promises';
const {chromium}=await import(process.env.SCROLLFACT_PLAYWRIGHT_MODULE||'playwright');
const result=JSON.parse(await fs.readFile(process.env.SCROLLFACT_RESULT,'utf8'));
const browser=await chromium.launch({executablePath:process.env.SCROLLFACT_BROWSER_PATH,headless:true});
try {
 const page=await browser.newPage({viewport:{width:440,height:900},deviceScaleFactor:2});
 let stage='requesting', complete=false;
 const progress={stage,paragraphs:result.passages.length,comments:result.comments.length,commentAreaDetected:true,images:result.images.length,imagesCompleted:result.images.length,imagesFailed:0,attempt:1,maxAttempts:6,retryAt:0};
 await page.addInitScript(result=>{window.chrome={runtime:{id:'qa',sendMessage:async()=>({tabId:1}),onMessage:{addListener:()=>{},removeListener:()=>{}}},tabs:{sendMessage:async(_id,m)=>{window.lastMessage=m;return m.type==='SF_CAPTURE_DOCUMENT'?{ok:true,snapshot:{snapshotId:result.snapshotId,...result.document,html:'<article>현재 기사</article>'}}:{ok:true,unmatchedIds:[]}}}};},result);
 await page.route('**/v1/**',route=>route.fulfill({status:route.request().method()==='POST'?202:200,json:route.request().url().includes('/reader/')?{id:null}:route.request().url().endsWith('/result')?result:{analysisId:result.analysisId,snapshotId:result.snapshotId,status:complete?'completed':'running',phase:'summarizing',sources:{total:0,completed:0,failed:0},progress:{...progress,stage}}}));
 await page.goto('http://127.0.0.1:5173/reader.html');
 await page.getByRole('button',{name:'이 페이지 분석하기',exact:true}).click();
 await page.getByText('AI 요청 1회째 · 최대 6회',{exact:true}).waitFor();
 assert.ok((await page.locator('.loading-source-note').innerText()).includes('본문에 외부 출처 링크가 없어'));
 assert.ok(!(await page.locator('.loading-progress').innerText()).includes('0/0'));
 stage='retry_wait';progress.attempt=2;progress.retryAt=Date.now()+8000;
 await page.getByText('AI 제공자 응답을 기다린 뒤 다시 시도해요',{exact:true}).waitFor();
 assert.ok((await page.locator('.loading-counts').innerText()).includes(`불러온 댓글 ${result.comments.length}개`));
 const dir=process.env.SCROLLFACT_UI_DIR||'/private/tmp/sf-live-qa';await fs.mkdir(dir,{recursive:true});
 await page.screenshot({path:dir+'/materials-progress.png',fullPage:true});
 stage='validating';await page.getByText('분석과 원문 연결을 확인하고 있어요',{exact:true}).waitFor();
 complete=true;await page.locator('.collection-note').waitFor();
 assert.ok((await page.locator('.collection-note').innerText()).includes(`본문 이미지 ${result.images.length}개`));
 const watched=await page.evaluate(()=>window.lastMessage);
 assert.equal(watched.type,'SF_WATCH_SECTIONS');
 assert.equal(watched.targets.length,result.passages.length+result.comments.length+result.images.length);
 await page.locator('.collected-comments>summary').click();
 assert.equal(await page.locator('.collected-comments .opinion-entry').count(),result.comments.length);
 await page.locator('.collected-comments .source-link').first().click();
 assert.equal((await page.evaluate(()=>window.lastMessage)).sectionId,result.comments[0].id);
 await page.locator('.collected-comments>summary').click();
 await page.locator('.collected-images>summary').click();
 assert.equal(await page.locator('.collected-images .opinion-entry').count(),result.images.length);
 await page.locator('.collected-images .source-link').last().click();
 assert.equal((await page.evaluate(()=>window.lastMessage)).sectionId,result.images.at(-1).id);
 await page.locator('.collected-images').screenshot({path:dir+'/materials-images.png'});
 await page.setViewportSize({width:320,height:900});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 console.log('PASS: immediate staged status, retry countdown, no 0/0, separate material counts, comment and image original-location actions.');
}finally{await browser.close();}
